function kidFriendlyWords(list, ch) {
  return list
    .filter((w) => typeof w === 'string')
    .map((w) => w.trim())
    .filter((w) => w.length >= 2 && w.length <= 4)
    .filter((w) => w.includes(ch))
    .filter((w) => [...w].every((c) => /[\u4e00-\u9fff]/.test(c)))
}

function wordsFromCnchar(ch) {
  try {
    const raw = cnchar.words(ch) || []
    return kidFriendlyWords(raw, ch)
  } catch {
    return []
  }
}

function fallbackWords(ch) {
  const pool = [`小${ch}`, `${ch}子`, `${ch}儿`, `${ch}花`, `${ch}人`]
  return pool.filter((w) => w.length >= 2)
}

function isWeakWord(w, ch) {
  if (w === ch + ch) return true
  if (w === `大${ch}` || w === `好${ch}` || w === `小${ch}`) return true
  return false
}

/** Template / meta sentences we never keep — empty is better than these. */
const TEMPLATE_SENTENCE_RE =
  /请用.+说一句|和小伙伴一起说|妈妈指着|图画书里看到了|教室黑板上写着|出现在这篇课文里|今天学了[“"]|请用耳朵认真听讲/

function isTemplateSentence(s) {
  return TEMPLATE_SENTENCE_RE.test(String(s || ''))
}

function naturalSentences(ch) {
  const bank = SENTENCE_BANK[ch]
  if (!bank?.length) return []
  // Only keep curated real sentences; never invent fill-in templates
  return bank.filter((s) => !isTemplateSentence(s)).slice(0, 3)
}

function hashSeed(ch) {
  return parseInt(createHash('md5').update(ch).digest('hex').slice(0, 8), 16)
}

function main() {
  const characters = JSON.parse(fs.readFileSync(dataPath, 'utf8'))
  const edu = loadEduWordMaps()
  let weakWords = 0
  let fromEdu = 0

  const enriched = characters.map((item) => {
    const ch = item.char
    const seed = hashSeed(ch)
    const eduWords = edu.get(ch) || []
    if (eduWords.length) fromEdu += 1
    const dictWords = wordsFromCnchar(ch)

    // Prefer textbook/edu words first, then dictionary, then fallbacks
    const merged = []
    const score = (w) => {
      let s = 0
      if (eduWords.includes(w)) s += 100
      if (!isWeakWord(w, ch)) s += 20
      if (w.length === 2) s += 10
      if (w.length === 3) s += 6
      if (w.length === 4) s += 3
      return s
    }
    const ranked = [...eduWords, ...dictWords, ...fallbackWords(ch)].sort(
      (a, b) => score(b) - score(a) || a.localeCompare(b, 'zh')
    )
    for (const w of ranked) {
      if (!w || merged.includes(w) || !w.includes(ch) || w.length < 2 || w.length > 4) continue
      if (isWeakWord(w, ch) && merged.length >= 2) continue
      merged.push(w)
    }

    // at least 2, prefer up to 5
    const n = Math.min(5, Math.max(2, 2 + (seed % 4)))
    let words = merged.slice(0, n)
    while (words.length < 2) {
      const extra = fallbackWords(ch).find((w) => !words.includes(w))
      if (!extra) break
      words.push(extra)
    }
    if (words.length < 2) weakWords += 1

    let sentences = naturalSentences(ch)
    // Keep previously filled everyday sentences (e.g. from Tatoeba) when bank has none
    if (!sentences.length && Array.isArray(item.sentences)) {
      sentences = item.sentences.filter((s) => s && !isTemplateSentence(s)).slice(0, 3)
    }
    return {
      char: ch,
      term: item.term,
      words,
      sentences,
    }
  })

  fs.writeFileSync(dataPath, JSON.stringify(enriched, null, 2), 'utf8')
  console.log(
    JSON.stringify(
      {
        total: enriched.length,
        withEduWords: fromEdu,
        weakWords,
        sample: [enriched[0], enriched.find((x) => x.char === '霜'), enriched[enriched.length - 1]],
      },
      null,
      2
    )
  )
}

main()
