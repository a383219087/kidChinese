function parseEduWords(text) {
  const map = new Map()
  // 天（天空）（今天）（天才） or 天(天空)(今天)
  const re = /([\u4e00-\u9fff])\s*[（(]\s*([^）)]+)\s*[）)](?:\s*[（(]\s*([^）)]+)\s*[）)])+/g
  let m
  while ((m = re.exec(text))) {
    const ch = m[1]
    const full = m[0]
    const words = [...full.matchAll(/[（(]\s*([^）)]+?)\s*[）)]/g)]
      .map((x) => x[1].replace(/\s+/g, ''))
      .flatMap((chunk) => chunk.split(/[、，,；;／/]/).map((s) => s.trim()))
      .filter((w) => w.length >= 2 && w.length <= 6 && [...w].every((c) => /[\u4e00-\u9fff]/.test(c)))
      .filter((w) => w.includes(ch))
    if (!words.length) continue
    if (!map.has(ch)) map.set(ch, [])
    const arr = map.get(ch)
    for (const w of words) {
      if (!arr.includes(w)) arr.push(w)
    }
  }
  return map
}

